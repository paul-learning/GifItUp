#!/usr/bin/env python3
"""Generates the reaction emoji table (ADR-0006 B10, `ann_reaction`) from the PyPI package `emoji` 2.14.1, so the list can
be rebuilt and compared. Run by hand when a new table version is made, never in CI:

    pip install emoji==2.14.1
    python3 -I scripts/gen-reaction-emojis.py shared/emoji-reactions-v1.tsv

Rules: fully qualified, Emoji 11.0 or older (Android 9 is the oldest supported release), one code point, optionally
followed by U+FE0F, so no skin tones, flags, keycaps, joiners or tag sequences; the skin-tone and regional-indicator
components themselves are left out, and so are text-like symbols (© ® ™, arrows, media controls, geometric shapes).
Output: index, hex code points, name; ascending code point order. The table is part of the format: never edit or reorder
a published version, a new list is a new file (`v2`).
"""
import sys

import emoji

MAX_EMOJI_VERSION = 11
EXCLUDED_RANGES = [
    (0x00A9, 0x00AE),  # © ®
    (0x203C, 0x2049),  # ‼ ⁉
    (0x2122, 0x2139),  # ™ ℹ
    (0x2190, 0x21FF),  # arrows
    (0x2328, 0x2328),  # keyboard
    (0x23CF, 0x23CF),  # eject
    (0x23E9, 0x23EF),  # media controls
    (0x23F8, 0x23FA),  # media controls
    (0x24C2, 0x24C2),  # circled M
    (0x25AA, 0x25AB),  # small squares
    (0x25B6, 0x25B6),
    (0x25C0, 0x25C0),
    (0x25FB, 0x25FE),  # geometric shapes
    (0x2640, 0x2642),  # gender signs (only useful inside sequences)
    (0x2695, 0x2695),
    (0x26A7, 0x26A7),
    (0x2934, 0x2935),
    (0x2B05, 0x2B07),  # arrows
    (0x3030, 0x3030),
    (0x303D, 0x303D),
    (0x3297, 0x3299),
    (0x1F1E6, 0x1F1FF),  # regional indicators (flags are pairs of them)
    (0x1F3FB, 0x1F3FF),  # skin-tone modifiers
]


def keep(text, data):
    codes = [ord(c) for c in text]
    one = len(codes) == 1 or (len(codes) == 2 and codes[1] == 0xFE0F)
    if not one or data["status"] != emoji.STATUS["fully_qualified"] or data["E"] > MAX_EMOJI_VERSION:
        return False
    return not any(lo <= codes[0] <= hi for lo, hi in EXCLUDED_RANGES)


def main(path):
    rows = sorted((ord(t[0]), t, d["en"].strip(":").replace("_", " ")) for t, d in emoji.EMOJI_DATA.items() if keep(t, d))
    with open(path, "w", encoding="utf-8", newline="\n") as out:
        out.write("# GifItUp reaction emoji table v1 (ADR-0006 B10). Never edit or reorder; a new list is a new file (v2).\n")
        out.write("# index<TAB>code points (hex, U+FE0F where the emoji needs it)<TAB>name. Generated by scripts/gen-reaction-emojis.py.\n")
        for index, (_, text, name) in enumerate(rows):
            out.write("%d\t%s\t%s\n" % (index, " ".join("%04X" % ord(c) for c in text), name))
    print(len(rows), "entries")


if __name__ == "__main__":
    main(sys.argv[1])
