package app.gifitup.mls

import kotlinx.coroutines.test.runTest
import java.io.File
import kotlin.io.encoding.Base64
import kotlin.io.encoding.ExperimentalEncodingApi
import kotlin.test.Test

/**
 * Writes `commonTest/.../InteropFixture.kt` for [InteropTest] (#26): two members, a group, the Welcome that adds Bob, and a
 * message sent after he joined, all made by the JVM (uniffi) binding. **Does nothing unless `GIFITUP_REGENERATE_INTEROP=1`**:
 * the fixture is committed, so a normal run never changes a file. Regenerate it when the MLS state or wire format of the crate
 * changes (the test then fails with an error code or a size), review the diff, commit it:
 * `GIFITUP_REGENERATE_INTEROP=1 ./gradlew :mls:jvmTest --tests '*InteropFixtureGenerator*'`.
 */
@OptIn(ExperimentalEncodingApi::class)
class InteropFixtureGenerator {
    private fun b64(bytes: ByteArray) = Base64.encode(bytes)

    @Test
    fun regenerate() =
        runTest {
            if (System.getenv("GIFITUP_REGENERATE_INTEROP") != "1") return@runTest
            val factory = UniffiMlsClientFactory
            val aliceKey = ByteArray(KEY) { 11 }
            val bobKey = ByteArray(KEY) { 13 }
            val alice = factory.create("alice", aliceKey.copyOf())
            val bob = factory.create("bob", bobKey.copyOf())
            val keyPackage = bob.createKeyPackages(1).single().keyPackage
            val groupId = alice.createGroup()
            val added = alice.prepareAdd(groupId, listOf(keyPackage))
            val epoch = alice.mergePending(groupId)
            val message = alice.encrypt(groupId, PLAINTEXT.encodeToByteArray())
            val welcome = checkNotNull(added.welcome)
            val aliceSignature = alice.publicIdentity().signaturePublicKey
            val bobSignature = bob.publicIdentity().signaturePublicKey
            val source =
                buildString {
                    appendLine("package app.gifitup.mls")
                    appendLine()
                    appendLine("/**")
                    appendLine(" * Generated by `InteropFixtureGenerator` (jvmTest, `GIFITUP_REGENERATE_INTEROP=1`); do not edit.")
                    appendLine(" * Test data of two throwaway identities and keys that protect nothing (no secrets); see `InteropTest`.")
                    appendLine(" */")
                    appendLine("internal object InteropFixture {")
                    appendLine("    const val PLAINTEXT = \"$PLAINTEXT\"")
                    appendLine("    const val EPOCH = ${epoch}L")
                    appendLine("    const val ALICE_KEY = \"${b64(aliceKey)}\"")
                    appendLine("    const val BOB_KEY = \"${b64(bobKey)}\"")
                    appendLine("    const val ALICE_SIGNATURE_KEY = \"${b64(aliceSignature)}\"")
                    appendLine("    const val BOB_SIGNATURE_KEY = \"${b64(bobSignature)}\"")
                    appendLine("    const val ALICE_FINGERPRINT = \"${b64(alice.fingerprint(aliceSignature))}\"")
                    appendLine("    const val BOB_FINGERPRINT = \"${b64(bob.fingerprint(bobSignature))}\"")
                    appendLine("    const val MESSAGE_REF = \"${b64(message.messageRef)}\"")
                    appendLine("    const val GROUP_ID = \"${b64(groupId)}\"")
                    listOf(
                        "WELCOME" to welcome,
                        "MESSAGE" to message.message,
                        "ALICE_STATE" to alice.exportState(),
                        "BOB_STATE" to bob.exportState(),
                    ).forEach { (name, bytes) ->
                        appendLine()
                        appendLine("    const val $name =")
                        appendLine("        \"\"\"")
                        b64(bytes).chunked(LINE).forEach { appendLine("        $it") }
                        appendLine("        \"\"\"")
                    }
                    appendLine("}")
                }
            File("src/commonTest/kotlin/app/gifitup/mls/InteropFixture.kt").writeText(source)
            alice.close()
            bob.close()
        }

    private companion object {
        const val KEY = 32
        const val LINE = 100
        const val PLAINTEXT = "hello bob, from the JVM"
    }
}
