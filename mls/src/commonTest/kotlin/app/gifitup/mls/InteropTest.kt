package app.gifitup.mls

import app.gifitup.shared.data.crypto.IncomingMessage
import kotlinx.coroutines.test.runTest
import kotlin.io.encoding.Base64
import kotlin.io.encoding.ExperimentalEncodingApi
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertIs

/**
 * Cross-binding interop (#26, ARCH-M2-7): a group made **on the JVM** (the uniffi binding Android uses) is read **by whichever
 * binding runs this test**, the JVM itself or the wasm binding in headless Chrome. The fixture holds two members' exported
 * snapshots, the Welcome that adds Bob and an application message sent after he joined, all produced by the JVM binding
 * ([InteropFixture], regenerated by `InteropFixtureGenerator`). Both bindings wrap the same Rust, so what can differ is the glue:
 * snapshot export and restore, byte encodings, fingerprints and the error mapping. The run on wasm is the cross-platform
 * check; the run on the JVM guards the fixture and the test itself.
 *
 * What it does **not** prove: a wasm-made group read on the JVM (the fixture is one way), the on-device Android runtime (the
 * alpha checklist covers it), or a whole chat through the real server (the end-to-end test does, with the JVM binding).
 * The fixture holds throwaway test identities ("alice", "bob") and keys that protect nothing; a Welcome and a message don't
 * expire with the key packages' lifetime, because joining skips that check (`group.rs`, `join`).
 */
@OptIn(ExperimentalEncodingApi::class)
class InteropTest {
    private fun bytes(base64: String) = Base64.decode(base64.filter { !it.isWhitespace() })

    @Test
    fun aGroupMadeOnTheJvmIsJoinedAndReadHere() =
        runTest {
            val factory = platformMlsClientFactory()
            val groupId = bytes(InteropFixture.GROUP_ID)
            factory.restore(bytes(InteropFixture.BOB_STATE), bytes(InteropFixture.BOB_KEY)).use { bob ->
                // The snapshot restores, and says who it is.
                assertEquals("bob", bob.publicIdentity().username)
                assertContentEquals(bytes(InteropFixture.BOB_SIGNATURE_KEY), bob.publicIdentity().signaturePublicKey)
                // The Welcome the JVM made opens here: sender and members as the JVM saw them.
                val info = bob.inspectWelcome(bytes(InteropFixture.WELCOME), groupId)
                assertEquals("alice", info.sender.username)
                assertEquals(listOf("alice", "bob"), info.members.map { it.username }.sorted())
                assertContentEquals(bytes(InteropFixture.ALICE_SIGNATURE_KEY), info.sender.signatureKey)
                // Fingerprints are the same bytes on every binding.
                assertContentEquals(bytes(InteropFixture.ALICE_FINGERPRINT), bob.fingerprint(info.sender.signatureKey))
                assertContentEquals(bytes(InteropFixture.BOB_FINGERPRINT), bob.fingerprint(bytes(InteropFixture.BOB_SIGNATURE_KEY)))
                assertContentEquals(groupId, bob.joinWelcome(info.token))
                assertEquals(2, bob.memberCount(groupId))
                assertEquals(InteropFixture.EPOCH, bob.epoch(groupId))
                // The application message sent after he joined decrypts here, from the sender the MLS signature names.
                val message = assertIs<IncomingMessage.Application>(bob.stageIncoming(groupId, bytes(InteropFixture.MESSAGE)))
                assertEquals(InteropFixture.PLAINTEXT, message.plaintext.decodeToString())
                assertEquals("alice", message.sender.username)
                assertContentEquals(bytes(InteropFixture.MESSAGE_REF), message.messageRef)
                // A restored snapshot of the joined state restores again (the glue's export and restore both ways).
                val again = factory.restore(bob.exportState(), bytes(InteropFixture.BOB_KEY))
                again.use { assertEquals(2, it.memberCount(groupId)) }
            }
        }

    @Test
    fun bothRestoredMembersTalkToEachOtherHere() =
        runTest {
            val factory = platformMlsClientFactory()
            val groupId = bytes(InteropFixture.GROUP_ID)
            factory.restore(bytes(InteropFixture.BOB_STATE), bytes(InteropFixture.BOB_KEY)).use { bob ->
                factory.restore(bytes(InteropFixture.ALICE_STATE), bytes(InteropFixture.ALICE_KEY)).use { alice ->
                    bob.joinWelcome(bob.inspectWelcome(bytes(InteropFixture.WELCOME), groupId).token)
                    // Bob answers; Alice, restored from the JVM's snapshot, reads it on this binding.
                    val reply = bob.encrypt(groupId, "hi alice, from the binding under test".encodeToByteArray())
                    val read = assertIs<IncomingMessage.Application>(alice.stageIncoming(groupId, reply.message))
                    assertEquals("hi alice, from the binding under test", read.plaintext.decodeToString())
                    assertEquals("bob", read.sender.username)
                    assertContentEquals(reply.messageRef, read.messageRef)
                }
            }
        }
}
