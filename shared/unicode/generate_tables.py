#!/usr/bin/env python3
"""Generates UnicodeTables.kt for the B3a text check (ADR-0006) from three UCD files of one Unicode version.

Usage: generate_tables.py <dir with UnicodeData.txt, PropList.txt, DerivedCoreProperties.txt> <version> <out.kt>

Standard library only. The output starts with the version and the SHA-256 of each source file, so a reviewer can
re-run it on files from unicode.org and compare. Moving to a newer Unicode version is a deliberate change (ADR-0006).
"""
import hashlib
import sys
from pathlib import Path

SOURCES = ("UnicodeData.txt", "PropList.txt", "DerivedCoreProperties.txt")


def merge(ranges):
    merged = []
    for lo, hi in sorted(ranges):
        if merged and lo <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], hi))
        else:
            merged.append((lo, hi))
    return merged


def property_ranges(path, name):
    found = []
    for line in path.read_text(encoding="utf-8").splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        span, prop = (part.strip() for part in body.split(";", 1))
        if prop == name:
            lo, _, hi = span.partition("..")
            found.append((int(lo, 16), int(hi or lo, 16)))
    return merge(found)


def category_ranges(path, category):
    """Code points of one general category; UnicodeData.txt marks ranges with <..., First> / <..., Last>."""
    found, first = [], None
    for line in path.read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        code, label, cat = int(fields[0], 16), fields[1], fields[2]
        if label.endswith(", First>"):
            first = code
        elif label.endswith(", Last>"):
            if cat == category:
                found.append((first, code))
            first = None
        elif cat == category:
            found.append((code, code))
    return merge(found)


def kotlin_array(name, doc, ranges):
    flat = ", ".join(f"0x{v:X}" for pair in ranges for v in pair)
    lines = []
    line = "        "
    for token in flat.split(", "):
        piece = token + ", "
        if len(line) + len(piece) > 118:
            lines.append(line.rstrip())
            line = "        "
        line += piece
    lines.append(line.rstrip())
    body = "\n".join(lines)
    return f"/** {doc} Pairs of first and last code point, sorted, merged. */\nval {name}: IntArray =\n    intArrayOf(\n{body}\n    )\n"


def main():
    source_dir, version, out = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])
    unicode_data, prop_list, derived = (source_dir / name for name in SOURCES)
    digests = "\n".join(
        f" * - `{name}`: `{hashlib.sha256((source_dir / name).read_bytes()).hexdigest()}`" for name in SOURCES
    )
    text = f"""@file:Suppress("MagicNumber", "ktlint:standard:argument-list-wrapping") // Generated tables.

package app.gifitup.shared.data.content

/*
 * GENERATED by shared/unicode/generate_tables.py: do not edit by hand (ADR-0006 B3a).
 *
 * Unicode version: {version}
 * Source files (UCD) and their SHA-256:
{digests}
 */

{kotlin_array("FORMAT_CHARACTERS", "General category Cf.", category_ranges(unicode_data, "Cf"))}
{kotlin_array("WHITE_SPACE", "Property White_Space.", property_ranges(prop_list, "White_Space"))}
{kotlin_array("DEFAULT_IGNORABLE", "Property Default_Ignorable_Code_Point.", property_ranges(derived, "Default_Ignorable_Code_Point"))}"""
    out.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
